"""Import talent positions from TauriShoot; explicit castable/granted spell mapping.
Run from repository root. Does not execute downloaded JavaScript.
"""
import concurrent.futures
import hashlib
import html
import json
import pathlib
import re
import urllib.request

ROOT = pathlib.Path(__file__).resolve().parent.parent
DATA = ROOT / 'assets/data'
ICONS = ROOT / 'assets/spells'
SPECS = [('Warlock · Destruction', 'warlock', 267), ('Warlock · Affliction', 'warlock', 265), ('Death Knight · Frost', 'death_knight', 251), ('Death Knight · Blood', 'death_knight', 250)]
ACTIVE = {48181,17877,48018,6789,5484,30283,205179,152108,196098,111400,108416,108503,63106,196447,206931,221699,206940,219809,194679,194844,206977,57330,194913,207167,207230,207256,152279,207127}
GRANTS = {48018:[48018],152107:[1122,18540],108501:[111859,111895,111896,111897]}

def fetch(url):
    with urllib.request.urlopen(url, timeout=40) as response:
        return response.read()

trees = {}
all_talents = {}
for label, file, spec in SPECS:
    raw = json.loads((DATA / f'{file}_source.json').read_text(encoding='utf-8-sig'))
    rows = []
    for row in raw['talents']:
        talents = []
        for cell in row:
            candidates = list(cell.values()) if isinstance(cell, dict) else cell
            selected = next((t for t in candidates if int(t['spec']) == spec), None)
            if selected is None:
                selected = next(t for t in candidates if int(t['spec']) == 0)
            talent = dict(selected)
            talent['id'] = int(talent['id'])
            talents.append(talent)
            all_talents[talent['id']] = talent
        assert len(talents) == 3
        rows.append(talents)
    assert len(rows) == 7
    trees[label] = rows

ids = set(all_talents) | {i for grants in GRANTS.values() for i in grants} | {47568}
def spell(spell_id):
    url = f'https://legion-shoot.tauri.hu/?spell={spell_id}'
    page = fetch(url).decode('utf-8')
    icon = re.search(r'_\['+str(spell_id)+r"\]\s*=\s*\{icon:'([^']+)'",page).group(1)
    name = html.unescape(re.search(r'<h1>(.*?)</h1>',page,re.S).group(1))
    tooltip = re.search(r'<div id="tooltip'+str(spell_id)+r'-generic-0"[^>]*>(.*?)</div>',page,re.S)
    description = html.unescape(re.sub(r'<[^>]+>', ' ', tooltip.group(1))) if tooltip else ''
    description = re.sub(r'\s+', ' ', description).strip()
    image_url = f'https://legion-static.tauri.hu/images/icons/large/{icon}.png'
    image = fetch(image_url)
    assert image.startswith(b'\x89PNG\r\n\x1a\n')
    (ICONS / f'{spell_id}.png').write_bytes(image)
    return spell_id, dict(name=name, description=description, icon=icon, source=url, image=image_url, sha256=hashlib.sha256(image).hexdigest())

with concurrent.futures.ThreadPoolExecutor(max_workers=3) as pool:
    details = dict(pool.map(spell, sorted(ids)))

result = {}
for label, rows in trees.items():
    result[label] = []
    for row in rows:
        converted = []
        for talent in row:
            tid = talent['id']
            grants = GRANTS.get(tid, [tid] if tid in ACTIVE else [])
            converted.append(dict(id=tid, name=talent['name'], description=details[tid]['description'],
                grants=[dict(id=i,name=details[i]['name']) for i in grants],
                replaces=[47568] if tid==207127 else [], source=details[tid]['source']))
        result[label].append(converted)
(DATA/'talents.json').write_text(json.dumps(result,ensure_ascii=False,indent=2),encoding='utf-8')
manifest_path = ICONS/'sources.json'
manifest = {int(x['spellId']):x for x in json.loads(manifest_path.read_text(encoding='utf-8-sig'))}
for sid,d in details.items():
    manifest[sid] = dict(spellId=sid, **{k:d[k] for k in ['icon','source','image','sha256']})
manifest_path.write_text(json.dumps(list(manifest.values()),ensure_ascii=False,indent=2),encoding='utf-8')
# Embed data in Dart to keep model initialization synchronous/offline and testable.
encoded = json.dumps(result,ensure_ascii=False)
(ROOT/'lib/talent_data.dart').write_text("// Generated by tools/build_talents.py from TauriShoot.\nconst talentJson = r'''"+encoded+"''';\n",encoding='utf-8')
print(f'Imported 84 talent choices and {len(details)} spell assets.')
for sid in sorted(ids):
    print(sid, details[sid]['description'])
